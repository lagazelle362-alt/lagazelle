const LANGUAGES = ["en", "fr", "ar"];
// The lines under a title show it in the other languages: [data-alt] in the
// second language, [data-third] in the remaining one.
const SECOND = { en: "ar", fr: "ar", ar: "en" };
const THIRD = { en: "fr", fr: "en", ar: "fr" };

const WHATSAPP_URL = "https://wa.me/22247906456?text=";
const EMAIL = "lagazelle362@gmail.com";
let currentLang = "en";
const languageButtons = document.querySelectorAll(".lang-switch [data-lang]");

function setLanguage(lang) {
  const t = translations[lang];
  currentLang = lang;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.title = t.title;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    if (t[element.dataset.i18n]) element.textContent = t[element.dataset.i18n];
  });
  document.querySelectorAll("[data-i18n-label]").forEach((element) => {
    if (t[element.dataset.i18nLabel]) element.setAttribute("aria-label", t[element.dataset.i18nLabel]);
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    if (t[element.dataset.i18nAlt]) element.alt = t[element.dataset.i18nAlt];
  });
  document.querySelectorAll("[data-wa]").forEach((link) => {
    link.href = WHATSAPP_URL + encodeURIComponent(t[link.dataset.wa]);
  });
  document.querySelectorAll("[data-mail]").forEach((link) => {
    link.href = "mailto:" + EMAIL + "?subject=" + encodeURIComponent(t[link.dataset.mail]);
  });

  for (const [attribute, pick] of [["alt", SECOND], ["third", THIRD]]) {
    const other = pick[lang];
    document.querySelectorAll("[data-" + attribute + "]").forEach((element) => {
      element.textContent = translations[other][element.dataset[attribute]];
      element.lang = other;
      element.dir = other === "ar" ? "rtl" : "ltr";
    });
  }

  languageButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === lang));
  });

  try { localStorage.setItem("lagazelle-language", lang); } catch (e) {}

  // Text and direction changed, so the scroll animation is rebuilt (motion.js).
  if (window.lgMotion) window.lgMotion.rebuild();
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    if (button.dataset.lang !== currentLang) setLanguage(button.dataset.lang);
  });
});

document.querySelector("#year").textContent = new Date().getFullYear();

let savedLang = null;
try { savedLang = localStorage.getItem("lagazelle-language"); } catch (e) {}
setLanguage(LANGUAGES.includes(savedLang) ? savedLang : "en");
